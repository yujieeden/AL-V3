#!/usr/bin/env python3
"""Generate VialDef.h from vial.json using VIA/VIAL minified LZMA data."""
import json
import lzma
import sys


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else "vial.json"
    destination = sys.argv[2] if len(sys.argv) > 2 else "VialDef.h"
    with open(source, "r", encoding="utf-8") as stream:
        definition = json.dumps(
            json.load(stream), separators=(",", ":")
        ).encode("utf-8")
    compressed = lzma.compress(definition)
    with open(destination, "w", encoding="ascii") as stream:
        stream.write("/* generated by vial_gen_def.py - do not edit */\n")
        stream.write("static const uint8_t vial_definition[] = {")
        stream.write(", ".join("0x{:02X}".format(byte) for byte in compressed))
        stream.write("};\n")
    print("{} -> {} ({} bytes)".format(source, destination, len(compressed)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
